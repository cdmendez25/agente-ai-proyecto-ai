    private static class CfrPolicy
    {
        public static readonly bool IsValid;
        public static readonly string Info;
        private static readonly byte[] Bytes;

        static CfrPolicy()
        {
            try
            {
                if (string.IsNullOrEmpty(PolicyData.Header)) { Info = "sin política entrenada"; return; }
                var campos = new Dictionary<string, string>();
                foreach (var par in PolicyData.Header.Split(';'))
                {
                    int i = par.IndexOf('=');
                    if (i > 0) campos[par.Substring(0, i)] = par.Substring(i + 1);
                }
                if (campos["v"] != StateEncoder.Version.ToString()) { Info = "versión distinta"; return; }
                if (campos["k"] != StateEncoder.NumKeys.ToString()) { Info = "número de claves distinto"; return; }
                if (campos["kc"] != StateEncoder.NumCoarseKeys.ToString()) { Info = "número de claves gruesas distinto"; return; }
                if (campos["h"] != StateEncoder.ConstantsHash().ToString()) { Info = "huella de abstracción distinta"; return; }
                var bytes = Convert.FromBase64String(string.Concat(PolicyData.Blob));
                if (bytes.Length != 2 * (StateEncoder.NumKeys + StateEncoder.NumCoarseKeys)) { Info = "tamaño incorrecto"; return; }
                if (campos["c"] != Checksum(bytes).ToString()) { Info = "suma de control incorrecta"; return; }
                Bytes = bytes;
                IsValid = true;
                Info = "ok " + PolicyData.Header;
            }
            catch (Exception e)
            {
                Info = "error al cargar: " + e.GetType().Name;
            }
        }

        public static uint Checksum(byte[] b)
        {
            uint h = 2166136261;
            for (int i = 0; i < b.Length; i++) { h ^= b[i]; h *= 16777619; }
            return h;
        }

        /// <summary>
        /// Distribución CFR: primero la clave fina; si esa situación no se aprendió, la gruesa.
        /// Devuelve 0 si no hay política, 1 si usó la fina, 2 si usó la gruesa.
        /// </summary>
        public static int TryGet(int fine, int coarse, PlayerObservation o, double[] pi)
        {
            if (!IsValid) return 0;
            if (fine >= 0 && fine < StateEncoder.NumKeys && Read(fine, o, pi)) return 1;
            if (coarse >= 0 && coarse < StateEncoder.NumCoarseKeys && Read(StateEncoder.NumKeys + coarse, o, pi)) return 2;
            return 0;
        }

        private static bool Read(int idx, PlayerObservation o, double[] pi)
        {
            int q0 = Bytes[2 * idx], q1 = Bytes[2 * idx + 1];
            if (q0 == 255 && q1 == 255) return false;                 // situación no aprendida
            pi[0] = q0 / 255.0;
            pi[1] = q1 / 255.0;
            pi[2] = Math.Max(0, 1 - pi[0] - pi[1]);
            ActionValidator.Mask(pi, o);
            return pi[0] + pi[1] + pi[2] > 1e-9;
        }
    }

