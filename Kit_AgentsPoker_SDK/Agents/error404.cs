    // StateEncoder v2: situación observable -> clave FINA (política principal) y clave GRUESA (respaldo).
    // Público: el entrenador usa EXACTAMENTE estas funciones para que entrenar y jugar coincidan.
    //
    // Clave fina (56 736): calle; mano (preflop: las 169 clases exactas; flop/turn: 6 niveles de HS x proyecto;
    //   river: 6 niveles); rivales que hablan después de mí; rivales activos; apuestas en la calle; si me apostaron;
    //   si YO ya aposté/subí en esta calle; quién fue el último agresor de la calle anterior (nadie/yo/otro);
    //   tamaño del bote (pequeño/grande).
    // Clave gruesa (3 564): la abstracción v1 (12 niveles preflop, sin los 3 últimos rasgos). Se usa si la fina
    //   no se vio lo suficiente en el entrenamiento.
    // =====================================================================================
    public static class StateEncoder
    {
        public const int Version = 2;

        /// <summary>Límites superiores de los 12 buckets preflop de la clave gruesa (percentil de PreflopPct).</summary>
        public static readonly double[] PreflopBins = { 0.02, 0.05, 0.08, 0.12, 0.17, 0.23, 0.30, 0.40, 0.50, 0.62, 0.78, 1.01 };
        /// <summary>Límites superiores de los 6 niveles de HS (fuerza de la mano tras el flop).</summary>
        public static readonly double[] HsBins = { 0.35, 0.50, 0.62, 0.74, 0.86, 1.01 };
        /// <summary>Bote "grande" si Pot >= PotBigBets * BetSize.</summary>
        public const int PotBigBets = 6;

        /// <summary>Rasgos de una situación (lo que el agente puede ver; nada oculto).</summary>
        public struct Features
        {
            public int Street, Cls169, Bucket, After, Opp, Bets, Facing, IAgg, Prev, PotBin;
            public double Strength;    // 0..1 (preflop: 1 - percentil; después: HS)
        }

        // Dimensiones por calle.
        private static readonly int[] NBucketCoarse = { 12, 12, 12, 6 };
        private static readonly int[] NBucketFine = { 169, 12, 12, 6 };
        private static readonly int[] NBets = { 4, 5, 5, 5 };
        private static readonly int[] OffCoarse = BuildOffsets(false);
        private static readonly int[] OffFine = BuildOffsets(true);
        public static readonly int NumCoarseKeys = OffCoarse[4];
        public static readonly int NumKeys = OffFine[4];

        private static int[] BuildOffsets(bool fine)
        {
            var off = new int[5];
            for (int s = 0; s < 4; s++)
            {
                int size = (fine ? NBucketFine[s] : NBucketCoarse[s]) * 3 * 3 * NBets[s] * 2;
                if (fine) size *= 2 * (s == 0 ? 1 : 3 * 2);        // IAgg; y después del flop: Prev (3) y PotBin (2)
                off[s + 1] = off[s] + size;
            }
            return off;
        }

        public static int PreflopBucket(double pct)
        {
            for (int i = 0; i < PreflopBins.Length; i++) if (pct <= PreflopBins[i]) return i;
            return PreflopBins.Length - 1;
        }

        public static int HsBucket(double hs)
        {
            for (int i = 0; i < HsBins.Length; i++) if (hs <= HsBins[i]) return i;
            return HsBins.Length - 1;
        }

        /// <summary>Bucket postflop: flop y turn = nivel de HS x 2 + (proyecto fuerte ? 1 : 0); river = nivel de HS.</summary>
        public static int PostflopBucket(int street, double hs, int drawClass)
        {
            int b = HsBucket(hs);
            return street == 3 ? b : b * 2 + (drawClass == 2 ? 1 : 0);
        }

        private static int Common(in Features f, int bucket)
        {
            int s = f.Street;
            int betIdx = s == 0 ? f.Bets - 1 : f.Bets;                 // preflop la BB ya cuenta como apuesta 1
            if (betIdx < 0) betIdx = 0;
            if (betIdx >= NBets[s]) betIdx = NBets[s] - 1;
            int after = f.After > 2 ? 2 : (f.After < 0 ? 0 : f.After);
            int opp = f.Opp < 1 ? 0 : (f.Opp > 3 ? 2 : f.Opp - 1);
            int x = bucket;
            x = x * 3 + after;
            x = x * 3 + opp;
            x = x * NBets[s] + betIdx;
            x = x * 2 + (f.Facing != 0 ? 1 : 0);
            return x;
        }

        /// <summary>Clave fina: junta todos los rasgos en un solo número (cifras con bases distintas).</summary>
        public static int EncodeFine(in Features f)
        {
            int x = Common(f, f.Street == 0 ? f.Cls169 : f.Bucket);
            x = x * 2 + (f.IAgg != 0 ? 1 : 0);
            if (f.Street > 0)
            {
                x = x * 3 + (f.Prev < 0 || f.Prev > 2 ? 0 : f.Prev);
                x = x * 2 + (f.PotBin != 0 ? 1 : 0);
            }
            return OffFine[f.Street] + x;
        }

        /// <summary>Clave gruesa (abstracción v1): respaldo para situaciones poco entrenadas.</summary>
        public static int EncodeCoarse(in Features f) => OffCoarse[f.Street] + Common(f, f.Bucket);

        /// <summary>Rasgos a partir de lo que ve el agente en el SDK (SdkObservationAdapter).</summary>
        public static Features FromObservation(PlayerObservation o, HandStrengthCalc hs)
        {
            var f = new Features();
            int street = (int)o.Street;
            if (street < 0 || street > 3) street = 3;
            f.Street = street;
            if (street == 0)
            {
                f.Cls169 = CardUtil.Canonical169(o.HoleCards[0], o.HoleCards[1]);
                double pct = CardUtil.PreflopPct[f.Cls169];
                f.Strength = 1 - pct;
                f.Bucket = PreflopBucket(pct);
            }
            else
            {
                float h = hs.Hs(o.HoleCards[0], o.HoleCards[1], o.Board);
                f.Strength = h;
                f.Bucket = PostflopBucket(street, h, hs.DrawClass(o.HoleCards[0], o.HoleCards[1], o.Board));
            }

            int n = o.Players.Count;
            int start = street == 0 ? (o.BigBlindSeat + 1) % n : (o.ButtonSeat + 1) % n;
            int myOrder = (o.Seat - start + n) % n;
            for (int j = 0; j < n; j++)
            {
                var pl = o.Players[j];
                if (j == o.Seat || !pl.IsActive || pl.IsAllIn) continue;
                if ((j - start + n) % n > myOrder) f.After++;
            }
            f.Opp = o.ActivePlayerCount - 1;
            f.Bets = o.BetsThisStreet;
            f.Facing = o.ToCall > 0 ? 1 : 0;
            f.PotBin = o.Pot >= PotBigBets * o.BetSize ? 1 : 0;

            // Historial público de la mano: ¿ya agredí en esta calle? ¿quién agredió último en la calle anterior?
            var hist = o.ActionHistory;
            if (hist != null)
            {
                int prevStreet = street - 1, lastPrev = -1;
                for (int i = 0; i < hist.Count; i++)
                {
                    var a = hist[i];
                    if (a.Kind != ActionKind.Bet && a.Kind != ActionKind.Raise) continue;
                    int s = (int)a.Street;
                    if (s == street && a.Seat == o.Seat) f.IAgg = 1;
                    if (s == prevStreet) lastPrev = a.Seat;
                }
                f.Prev = street == 0 || lastPrev < 0 ? 0 : (lastPrev == o.Seat ? 1 : 2);
            }
            return f;
        }

        /// <summary>Huella de las constantes de la abstracción: la política guardada solo se usa si coincide.</summary>
        public static uint ConstantsHash()
        {
            uint h = 2166136261;
            void Mix(long v) { for (int i = 0; i < 8; i++) { h ^= (byte)(v >> (8 * i)); h *= 16777619; } }
            Mix(Version); Mix(NumKeys); Mix(NumCoarseKeys); Mix(PotBigBets);
            foreach (var d in PreflopBins) Mix(BitConverter.DoubleToInt64Bits(d));
            foreach (var d in HsBins) Mix(BitConverter.DoubleToInt64Bits(d));
            return h;
        }
    }

